/* 12 зон × (3 моба + босс). Арт — из референсов (tools/cut_zones.py): z{N}_bg, z{N}_m{1..4}_{idle|attack|hurt|death}.
   Имена мобов — рабочие (П), их можно менять здесь без правки кода. Фон меняется каждые 50 этажей (У). */
(function (PZ) {
  PZ.ZONES = [
    { name: 'Древний лес',         mobs: ['Лесной волк', 'Споровик', 'Корапаук'],               boss: 'Древний страж рощи' },
    { name: 'Пепельная пустыня',   mobs: ['Песчаный скорпион', 'Пустынный упырь', 'Песчаный элементаль'], boss: 'Пепельный жрец' },
    { name: 'Ледяные залы',        mobs: ['Ледяной волк', 'Морозный призрак', 'Ледяной голем'], boss: 'Королева метели' },
    { name: 'Огненная кузница',    mobs: ['Огненный бес', 'Адская гончая', 'Рыцарь пламени'],   boss: 'Владыка кузни' },
    { name: 'Грозовой пик',        mobs: ['Грозовой гриф', 'Дух молний', 'Громовой голем'],    boss: 'Повелитель бури' },
    { name: 'Ядовитое болото',     mobs: ['Ядовитая жаба', 'Болотный упырь', 'Гнойный паук'],   boss: 'Болотная гидра' },
    { name: 'Затопленный храм',    mobs: ['Глубинный воин', 'Панцирный краб', 'Водный элементаль'], boss: 'Морской змей' },
    { name: 'Царство смерти',      mobs: ['Рыцарь смерти', 'Костяная гончая', 'Плакальщица'],   boss: 'Король-лич' },
    { name: 'Кристальные пещеры',  mobs: ['Кристальный голем', 'Кристальный жук', 'Осколочный дух'], boss: 'Кристальный дракон' },
    { name: 'Священная цитадель',  mobs: ['Крылатый страж', 'Сияющая сфера', 'Золотой паладин'], boss: 'Серафим' },
    { name: 'Теневая крепость',    mobs: ['Теневой клинок', 'Теневой зверь', 'Теневой рыцарь'], boss: 'Владыка теней' },
    { name: 'Бездна',              mobs: ['Щупальцевый ужас', 'Око Бездны', 'Демон Бездны'],    boss: 'Порождение Бездны' },
  ];
  // Враг этажа: зона циклически повторяется после 12-й (новые измерения — по мере выпуска арта).
  PZ.enemyOf = function (floor, idx, bossKind) {
    const zi = Math.floor((floor - 1) / 50) % PZ.ZONES.length, z = PZ.ZONES[zi];
    if (bossKind) {
      if (floor === 400) return { zone: 8, mob: 4, name: 'Хранитель Цикла', boss: true };
      if (bossKind === 'boss50') return { zone: zi + 1, mob: 4, name: z.boss, boss: true };
      // 10-й и 25-й — усиленный обычный моб зоны (пока нет отдельного арта полубоссов)
      const m = (Math.floor(floor / 10)) % 3;
      return { zone: zi + 1, mob: m + 1, name: (bossKind === 'boss25' ? 'Вожак: ' : 'Свирепый ') + z.mobs[m].toLowerCase(), boss: true, mini: true };
    }
    const m = (floor + idx) % 3;
    return { zone: zi + 1, mob: m + 1, name: z.mobs[m], boss: false };
  };
})(globalThis.PZ = globalThis.PZ || {});

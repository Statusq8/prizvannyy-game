const test = require('node:test'), assert = require('node:assert');
const load = require('./load');
test('Режим тестировщика: ресурсы, прыжок, сейв помечен и проходит проверку', () => {
  const PZ = load(), s = PZ.state.newGame();
  assert.ok(!s.account.tester);
  const g = PZ.tester.gold(s, 1000); assert.ok(g >= 1e4 && s.run.gold >= g);
  PZ.tester.scrolls(s, 100); assert.ok(s.account.scrolls >= 100);
  PZ.tester.shards(s, 1000); assert.strictEqual(s.account.shards, 1000);
  assert.strictEqual(PZ.tester.bones(s, 3, 6), 36); assert.strictEqual(s.account.bones.head_3, 6);
  PZ.tester.mainLevels(s, 100); assert.strictEqual(s.run.mainLevel, 101);
  assert.strictEqual(PZ.tester.jump(s, 250), 250);
  assert.strictEqual(s.run.cleared, 249); assert.strictEqual(s.account.record, 249); assert.strictEqual(PZ.combat.currentFloor(s), 250);
  PZ.tester.jump(s, 10); assert.strictEqual(s.account.record, 249, 'рекорд не падает');
  const n = PZ.tester.allHeroes(s); assert.ok(n > 0);
  assert.ok(!Object.keys(s.account.owned).some(id => ['SS', 'БОГ'].includes(PZ.HERO_BY_ID[id].rarity)), 'SS/БОГ закрыты рекордом');
  PZ.tester.hireAll(s); PZ.tester.jump(s, 250); PZ.tester.fillEnergy(s);
  PZ.combat.events.length = 0; for (let i = 0; i < 30; i++) PZ.combat.tick(s, 0.1);
  assert.ok(PZ.combat.events.some(e => e.t === 'ult'), 'после заполнения энергии ульта сработала');
  assert.strictEqual(s.account.tester, true);
  assert.deepStrictEqual(PZ.state.validate(s), []);
  const back = PZ.save.deserialize(PZ.save.serialize(s)).state; assert.strictEqual(back.account.tester, true);
});
test('Перелёт ульты: урон сверх добивания уходит следующему врагу', () => {
  const PZ = load(), s = PZ.state.newGame();
  PZ.tester.jump(s, 3); const b = PZ.combat.ensureBattle(s); b.spawnWait = 0;
  s.run.ultCarry = b.maxHp * 1.5;
  PZ.combat.tick(s, 0.001);
  assert.strictEqual(s.run.battle.idx, 1, 'первый враг убит перелётом');
  b.spawnWait = 0; PZ.combat.tick(s, 0.001);
  assert.strictEqual(s.run.ultCarry, 0);
  assert.ok(s.run.battle.hp < s.run.battle.maxHp * 0.6, 'второй получил остаток');
  PZ.combat.goToRecord(s); assert.strictEqual(s.run.ultCarry, 0);
});

  function allQuests() { const Q = CONFIG.quests; return [...Q.daily.map(q => ({ ...q, period: 'daily' })), ...Q.weekly.map(q => ({ ...q, period: 'weekly' })), ...Q.intro.map(q => ({ ...q, period: 'intro' })), ...Q.ritual.map(q => ({ ...q, period: 'ritual' }))]; }

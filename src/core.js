  function addEventPoints(s, n) {
    if (!s.event || !s.event.id || !n) return;
    s.event.points += n;
    CONFIG.events.milestones.forEach((m, i) => {
      if (s.event.points >= m.at && !s.event.ms[i]) {
        s.event.ms[i] = true;
        inboxAdd(s, 'Событие «' + currentEvent(s).name + '»: ' + m.at + ' очков', m.reward);
      }
    });
  }
